-- ----------------------------------------------------------------------------
-- profiles (replaces legacy `users` table; linked to Supabase Auth)
-- ----------------------------------------------------------------------------
create table if not exists public.profiles (
  id              uuid primary key default gen_random_uuid(),
  auth_id         uuid unique references auth.users (id) on delete set null,
  legacy_id       bigint unique,
  name            text not null,
  email           text not null unique,
  phone           text,
  role            text not null default 'ROLE_USER'
                  check (role in ('ROLE_USER', 'ROLE_OWNER', 'ROLE_ADMIN')),
  bio             text,
  city            text,
  profile_picture text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- Helper functions (used by RLS policies)
-- ----------------------------------------------------------------------------
create or replace function public.current_profile_id()
returns uuid
language sql stable security definer
set search_path = public
as $$
  select id from public.profiles where auth_id = auth.uid();
$$;

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select coalesce(
    (select role = 'ROLE_ADMIN' from public.profiles where auth_id = auth.uid()),
    false
  );
$$;

create or replace function public.is_staff()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select coalesce(
    (select role in ('ROLE_ADMIN', 'ROLE_OWNER') from public.profiles where auth_id = auth.uid()),
    false
  );
$$;

