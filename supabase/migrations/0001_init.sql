-- Keep pgs.rating / pgs_reviews_count in sync on every review change.
create or replace function public.refresh_pg_rating()
returns trigger
language plpgsql security definer
set search_path = public
as $$
declare
  target bigint;
begin
  target := coalesce(new.pg_id, old.pg_id);
  update public.pgs p set
    rating = (
      select coalesce(round(avg(r.rating)::numeric, 2)::double precision, 0)
      from public.reviews r where r.pg_id = target
    ),
    reviews_count = (
      select count(*) from public.reviews r where r.pg_id = target
    )
  where p.id = target;
  return coalesce(new, old);
end;
$$;

drop trigger if exists trg_refresh_pg_rating on public.reviews;
create trigger trg_refresh_pg_rating
  after insert or update or delete on public.reviews
  for each row execute function public.refresh_pg_rating();

